#!/usr/bin/env node
// gen-precache — regenerates the precache list inside app/sw.js (plan Phase 5.1;
// with no build step, this dev-only script is the precache manifest pipeline).
// Run on change: node tools/gen-precache.mjs
import { readdirSync, statSync, readFileSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';

const appDir = new URL('../app', import.meta.url).pathname;
const SKIP = /node_modules|test-results|playwright-report|\/e2e\/|\/tests\/|playwright\.config|package(-lock)?\.json|tsconfig/;

/** @param {string} dir @returns {string[]} */
function walk(dir) {
  return readdirSync(dir).flatMap((f) => {
    const p = join(dir, f);
    return statSync(p).isDirectory() ? walk(p) : [p];
  });
}

const files = walk(appDir)
  .filter((p) => !SKIP.test(p))
  .map((p) => './' + relative(appDir, p))
  .sort();

const swPath = join(appDir, 'sw.js');
const sw = readFileSync(swPath, 'utf8');
const stamp = new Date().toISOString().slice(0, 10);
const block = `// GENERATED by tools/gen-precache.mjs ${stamp} — do not edit by hand
const PRECACHE = ${JSON.stringify(files, null, 2)};
// END GENERATED`;
const out = sw.replace(
  /\/\/ GENERATED by tools\/gen-precache\.mjs[\s\S]*?\/\/ END GENERATED/,
  block);
if (out === sw) {
  console.error('✗ sw.js is missing the GENERATED markers');
  process.exit(1);
}
writeFileSync(swPath, out);
console.log(`✓ ${files.length} files in precache manifest`);
